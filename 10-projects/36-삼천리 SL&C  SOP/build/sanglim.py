def won(v):
    return "{:,}원".format(v)


def build_menu():
    items = []
    for i, (chip, name, price, grp, comp, desc, ware, note) in enumerate(ITEMS, 1):
        img = None
        if name in PHOTO_CROP:
            img, _ = save_jpg(menu_photo(name), P_("m%02d.jpg" % i), maxside=1000, q=88)
        sec = []
        if comp:
            sec.append(dict(en="COMPONENTS", kr="구성 · 중량", lines=[comp]))
        if desc:
            sec.append(dict(en="DESCRIPTION", kr="메뉴 설명", lines=[desc]))
        if ware:
            sec.append(dict(en="SERVEWARE", kr="제공 기물", lines=ware))
        if note:
            sec.append(dict(en="NOTE", kr="주의 · 안내", lines=note))
        price_s = won(price) + (" · 2인" if "(2인)" in name else "")
        items.append(dict(page=i, code="", chip=chip, en=name, kr="", price=price_s, img=img,
                          pending=img is None and chip != "음료 · 주류", sections=sec, grp=grp))
    return items


