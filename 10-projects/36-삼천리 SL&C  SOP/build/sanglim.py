def P_(name):
    return "sanglim-" + name


def open_img(path):
    return ImageOps.exif_transpose(Image.open(path)).convert("RGB")


def src_jpg(path, name, maxside=1000, box=None):
    im = open_img(path)
    if box:
        W, H = im.size
        im = im.crop((int(box[0] * W), int(box[1] * H), int(box[2] * W), int(box[3] * H)))
    return save_jpg(im, P_(name), maxside=maxside)


