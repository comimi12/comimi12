# ── 이미지 ─────────────────────────────────────────────
def save_jpg(im, name, maxside=1000, q=84):
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
        bg.alpha_composite(im)
        im = bg
    im = im.convert("RGB")
    if max(im.size) > maxside:
        im.thumbnail((maxside, maxside), Image.LANCZOS)
    im.save(os.path.join(IMG, name), "JPEG", quality=q, optimize=True, progressive=True)
    return "img/" + name, im.size


_prs = None


def pptx_pic(slide, shape_name, name, maxside=1000):
    """입문 매뉴얼 PPTX의 그림 원본(고해상도)을 그대로 쓴다."""
    global _prs
    from pptx import Presentation
    if _prs is None:
        _prs = Presentation(PPTX)

    def walk(shs):
        for s in shs:
            if s.shape_type == 6:
                yield from walk(s.shapes)
            else:
                yield s
    for s in walk(_prs.slides[slide - 1].shapes):
        if s.name == shape_name and "PICTURE" in str(s.shape_type):
            return save_jpg(Image.open(io.BytesIO(s.image.blob)), name, maxside)
    raise SystemExit("[ERR] 그림 없음: slide %d / %s" % (slide, shape_name))


_pdfs = {}


def pdf_crop(path, page, box, name, dpi=200, unit="in"):
    """PDF 페이지 일부를 잘라 저장. box=(x, y, w, h) — 입문 매뉴얼은 PPTX 인치 좌표 그대로."""
    import fitz
    d = _pdfs.get(path) or _pdfs.setdefault(path, fitz.open(path))
    k = 72.0 if unit == "in" else 1.0
    x, y, w, h = box
    clip = fitz.Rect(x * k, y * k, (x + w) * k, (y + h) * k)
    pix = d[page - 1].get_pixmap(dpi=dpi, clip=clip)
    im = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
    return save_jpg(im, name, maxside=1400, q=86)


def img_entry(rel_size, y, **kw):
    rel, (w, h) = rel_size
    e = dict(src=rel, y=y, x=0, w=6.0, h=round(6.0 * h / w, 2))
    e.update(kw)
    return e


# ── SOP 페이지 ─────────────────────────────────────────
def B(head, lines, kind="normal", **kw):
    b = dict(head=head, lines=lines, kind=kind, x=0, w=6.7)
    b.update(kw)
    return b


def page(n, title, items, badge="", tables=None, checklist=None):
    """items = 블록·이미지를 화면 순서대로. y는 순번으로 매긴다(앱이 y로 정렬)."""
    blocks, images = [], []
    for i, it in enumerate(items):
        it["y"] = float(i)
        (images if "src" in it else blocks).append(it)
    return dict(n=n, title=title, badge=badge, chapter="", ch="", divider=False,
                blocks=blocks, images=images, tables=tables or [], checklist=checklist or [])


