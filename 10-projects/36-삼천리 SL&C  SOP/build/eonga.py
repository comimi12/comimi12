def won(v):
    return "{:,}원".format(v)


def build_menu():
    items = []
    for i, (chip, name, price, photo, grp, spec, comp, desc, ware, say, note) in enumerate(ITEMS, 1):
        img = None
        if photo:
            img, _ = save_jpg(Image.open(os.path.join(PHOTO, photo)), "eonga-m%02d.jpg" % i, maxside=1000, q=84)
        sec = []
        if comp:
            sec.append(dict(en="COMPONENTS", kr="구성", lines=[comp]))
        if spec:
            sec.append(dict(en="SPEC", kr="원산지 · 중량", lines=[spec]))
        if desc:
            sec.append(dict(en="DESCRIPTION", kr="메뉴 설명", lines=[desc]))
        if ware:
            sec.append(dict(en="SERVEWARE", kr="제공 기물", lines=ware))
        if say:
            sec.append(dict(en="SERVICE SCRIPT", kr="제공 멘트", lines=say))
        if note:
            sec.append(dict(en="NOTE", kr="주의 · 안내", lines=note))
        price_s = won(price) + (" · 1인" if chip in ("한상차림", "스페셜 한상차림") else "")
        items.append(dict(page=i, code="", chip=chip, en=name, kr="", price=price_s, img=img,
                          pending=img is None, sections=sec, grp=grp))
    return items


